import { test, expect } from '@playwright/test'

const KEY = 'zhumeng-crm:v1'
const makeCustomer = (n, status = '潜在客户') => ({ id: `test-${n}`, name: `客户${n}`, company: `筑梦科技${n}有限公司`, phone: `1380013${String(n).padStart(4, '0')}`, email: '', status, notes: '', createdAt: `2026-10-${String(n + 1).padStart(2, '0')}T08:00:00.000Z` })
async function seed(page, customers) {
  await page.goto('/')
  await page.evaluate(({ key, customers }) => localStorage.setItem(key, JSON.stringify({ version: 1, customers })), { key: KEY, customers })
  await page.reload()
}
async function addCustomer(page, name = '张晓明') {
  await page.getByRole('button', { name: '新增客户', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('客户姓名').fill(name)
  await dialog.getByLabel('公司名称').fill('上海筑梦科技有限公司')
  await dialog.getByLabel('联系电话').fill('13800138000')
  await dialog.getByLabel('电子邮箱').fill('zhang@example.com')
  await dialog.getByLabel('备注信息').fill('下周跟进企业服务需求')
  await dialog.getByRole('button', { name: '创建客户' }).click()
  await expect(dialog).not.toBeVisible()
}

test('空列表、新增、刷新持久化、编辑、删除确认与统计', async ({ page }) => {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page.getByText('从第一位客户，开启新的合作')).toBeVisible()
  await expect(page.getByTestId('stat-green')).toHaveText('0位')
  await addCustomer(page)
  await expect(page.getByRole('cell', { name: '张晓明 zhang@example.com' })).toBeVisible()
  await expect(page.getByTestId('stat-green')).toHaveText('1位')
  await page.reload()
  await expect(page.getByRole('button', { name: '编辑客户 张晓明', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '编辑客户 张晓明', exact: true }).click()
  await expect(page.getByLabel('备注信息')).toHaveValue('下周跟进企业服务需求')
  await page.getByLabel('客户姓名').fill('张晓明（已联系）')
  await page.getByRole('dialog').getByLabel('客户状态').selectOption('跟进中')
  await page.getByRole('button', { name: '保存修改' }).click()
  await expect(page.getByTestId('stat-blue')).toHaveText('1位')
  await page.getByRole('button', { name: '编辑客户 张晓明（已联系）', exact: true }).click()
  await page.getByRole('dialog').getByLabel('客户状态').selectOption('已成交')
  await page.getByRole('button', { name: '保存修改' }).click()
  await expect(page.getByTestId('stat-blue')).toHaveText('0位')
  await expect(page.getByTestId('stat-purple')).toHaveText('1位')
  await page.getByRole('button', { name: '删除客户 张晓明（已联系）', exact: true }).click()
  await page.getByRole('button', { name: '取消', exact: true }).click()
  await expect(page.getByRole('button', { name: '编辑客户 张晓明（已联系）', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '删除客户 张晓明（已联系）', exact: true }).click()
  await page.getByRole('button', { name: '确认删除', exact: true }).click()
  await expect(page.getByTestId('stat-green')).toHaveText('0位')
  await page.reload()
  await expect(page.getByText('从第一位客户，开启新的合作')).toBeVisible()
  expect(errors).toEqual([])
})

test('按姓名、公司、电话搜索，按状态筛选，分页和删除末页记录', async ({ page }) => {
  await seed(page, Array.from({ length: 9 }, (_, i) => makeCustomer(i, i % 2 ? '跟进中' : '已成交')))
  await expect(page.locator('tbody tr')).toHaveCount(8)
  await page.getByRole('button', { name: '下一页', exact: true }).click()
  await expect(page.locator('tbody tr')).toHaveCount(1)
  await page.getByRole('button', { name: '删除客户 客户0', exact: true }).click()
  await page.getByRole('button', { name: '确认删除', exact: true }).click()
  await expect(page.locator('tbody tr')).toHaveCount(8)
  await expect(page.getByRole('button', { name: '下一页', exact: true })).toBeDisabled()
  for (const query of ['客户3', '筑梦科技3', '13800130003']) {
    await page.getByRole('textbox', { name: '搜索客户' }).fill(query)
    await expect(page.locator('tbody tr')).toHaveCount(1)
    await expect(page.locator('tbody')).toContainText('客户3')
  }
  await page.getByRole('button', { name: '清空搜索' }).click()
  await page.getByRole('tab', { name: '跟进中', exact: true }).click()
  await expect(page.locator('tbody tr')).toHaveCount(4)
  await page.getByRole('textbox', { name: '搜索客户' }).fill('无匹配')
  await expect(page.getByText('暂时没有匹配的客户')).toBeVisible()
  await page.getByRole('button', { name: '重置筛选' }).click()
  await expect(page.locator('tbody tr')).toHaveCount(8)
  await page.getByRole('button', { name: '查看已成交 4' }).click()
  await expect(page.locator('tbody tr')).toHaveCount(4)
})

