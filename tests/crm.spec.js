test('导出完整数据、导入合并去重、拒绝无效备份', async ({ page }) => {
  await seed(page, [makeCustomer(1)])
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: '导出客户', exact: true }).click()
  const download = await downloadPromise
  const stream = await download.createReadStream()
  let text = ''
  for await (const chunk of stream) text += chunk.toString()
  expect(JSON.parse(text).customers).toHaveLength(1)
  expect(JSON.parse(text).customers[0].name).toBe('客户1')
  await page.getByRole('button', { name: '数据与备份' }).click()
  const input = page.getByLabel('选择客户备份文件')
  await input.setInputFiles({ name: 'invalid.json', mimeType: 'application/json', buffer: Buffer.from('{broken') })
  await expect(page.getByRole('alert')).toContainText('无法识别此文件')
  await input.setInputFiles({ name: 'backup.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify({ version: 1, customers: [makeCustomer(1), makeCustomer(2)] })) })
  await page.getByRole('button', { name: '确认导入' }).click()
  await expect(page.getByTestId('stat-green')).toHaveText('2位')
  await page.reload()
  await expect(page.locator('tbody tr')).toHaveCount(2)
})

test('存储损坏时保护原始数据，写入失败时不假报成功', async ({ page }) => {
  await page.goto('/')
  await page.evaluate(key => localStorage.setItem(key, 'broken original data'), KEY)
  await page.reload()
  await expect(page.getByRole('alert')).toContainText('已暂停写入')
  await expect(page.getByRole('button', { name: '新增客户', exact: true })).toBeDisabled()
  expect(await page.evaluate(key => localStorage.getItem(key), KEY)).toBe('broken original data')
  await page.evaluate(key => localStorage.removeItem(key), KEY)
  await page.reload()
  await page.evaluate(() => { Storage.prototype.setItem = () => { throw new DOMException('Quota exceeded', 'QuotaExceededError') } })
  await page.getByRole('button', { name: '新增客户', exact: true }).click()
  await page.getByLabel('客户姓名').fill('测试')
  await page.getByLabel('公司名称').fill('测试公司')
  await page.getByLabel('联系电话').fill('13800138000')
  await page.getByRole('button', { name: '创建客户' }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await expect(page.getByRole('dialog').getByRole('alert')).toContainText('保存失败')
  await expect(page.getByTestId('stat-green')).toHaveText('0位')
})

test('同一浏览器的标签页同步客户变化', async ({ page, context }) => {
  await page.goto('/')
  const second = await context.newPage()
  await second.goto('/')
  await addCustomer(page, '多标签页客户')
  await expect(second.getByRole('button', { name: '编辑客户 多标签页客户', exact: true })).toBeVisible()
  await expect(second.getByTestId('stat-green')).toHaveText('1位')
})

